CREATE TABLE IF NOT EXISTS tw_h5_pay_order (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    mch_order_no VARCHAR(64) NOT NULL COMMENT '天问商户唯一订单号',
    gateway_order_no VARCHAR(64) DEFAULT NULL COMMENT '星汇 NexaVault 网关订单号',
    user_id BIGINT NOT NULL COMMENT 'H5 用户 ID',
    order_type VARCHAR(24) NOT NULL COMMENT 'unlock=单场解锁, member=会员开通',
    plan_code VARCHAR(32) NOT NULL COMMENT 'unlock / vip / svip / king',
    title VARCHAR(160) NOT NULL COMMENT '订单标题',
    recommendation_id VARCHAR(64) DEFAULT NULL COMMENT '单场解锁关联推荐 ID',
    vip_level INT NOT NULL DEFAULT 0 COMMENT '开通会员等级 1=VIP 2=SVIP 3=至尊VIP',
    vip_days INT NOT NULL DEFAULT 0 COMMENT '开通会员有效天数',
    usd_amount DECIMAL(18,6) NOT NULL COMMENT '应付美元稳定币基准金额',
    cny_amount DECIMAL(18,2) DEFAULT NULL COMMENT '参考人民币对账金额',
    chain_key VARCHAR(32) NOT NULL DEFAULT 'auto' COMMENT '公链标识 auto/tron/arb/bsc/base/polygon/solana',
    coin VARCHAR(24) NOT NULL DEFAULT 'USDT' COMMENT '币种 USDT/USDC',
    expected_amount VARCHAR(64) DEFAULT NULL COMMENT '收银台分配防撞尾数金额',
    actual_amount VARCHAR(64) DEFAULT NULL COMMENT '实际链上到账金额',
    pay_address VARCHAR(128) DEFAULT NULL COMMENT '链上收款地址',
    qr_content VARCHAR(512) DEFAULT NULL COMMENT '收款二维码内容',
    deep_link VARCHAR(512) DEFAULT NULL COMMENT '钱包拉起 DeepLink',
    checkout_url VARCHAR(512) DEFAULT NULL COMMENT '星汇托管收银台 URL',
    tx_hash VARCHAR(128) DEFAULT NULL COMMENT '链上交易哈希',
    status VARCHAR(24) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING / PAID / EXPIRED / FAILED',
    fulfilled TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否已完成会员/解锁履约',
    expire_at BIGINT DEFAULT NULL COMMENT '过期毫秒时间戳',
    paid_at DATETIME DEFAULT NULL COMMENT '支付完成时间',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mch_order_no (mch_order_no),
    KEY idx_user_created (user_id, created_at),
    KEY idx_gateway_order_no (gateway_order_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='天问AI多链收银台订单表';
